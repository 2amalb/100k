-- EGOX · Локации 100k — схема базы для Supabase
-- Запуск: Supabase → SQL Editor → вставить весь файл → Run. Потом так же seed.sql.
-- Принципы: ничего не удаляется; каждое изменение пишется в audit_log автоматически;
-- доступ только у почт из team_members.

-- ============ Таблицы ============

create table if not exists public.team_members (
  email      text primary key,
  name       text not null,
  role       text not null default 'field' check (role in ('admin','field')),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id      text primary key,            -- '01'..'11'
  name_ru text not null,
  name_en text not null,               -- название L1 у заказчика
  sort    int  not null
);

create table if not exists public.location_types (
  id            text primary key,      -- '01-01'
  category_id   text not null references public.categories(id),
  name_ru       text not null,
  name_en       text not null,         -- название L2 у заказчика
  plan_hours    int  not null check (plan_hours >= 0),
  outdoor_share numeric(4,2) not null default 0 check (outdoor_share between 0 and 1),
  typical_size  text not null check (typical_size in ('S','M','L')),
  sort          int  not null
);

create table if not exists public.locations (
  id             bigint generated by default as identity primary key,
  name           text not null check (length(trim(name)) > 0),
  people         int  check (people > 0),
  site           text check (site in ('Завод','Площадка','Рынок')),
  region         text,
  status         text not null default 'Новая'
                 check (status in ('Новая','Переговоры','Договорились','Запущена','Отказ','Не подходит')),
  project        text check (project in ('100k','2000','1500')),
  type_id        text references public.location_types(id),
  hours_override int  check (hours_override > 0),   -- если часов меньше лимита
  planned_date   date,
  owner          text,
  contact        text,
  phone          text,
  next_step      text,
  note           text,
  created_at     timestamptz not null default now(),
  created_by     text,
  updated_at     timestamptz not null default now(),
  updated_by     text
);

create table if not exists public.visits (
  id          bigint generated by default as identity primary key,
  location_id bigint not null references public.locations(id),
  visit_date  date not null,
  who         text not null,
  goal        text,
  result      text check (result in ('Договорились','Думает','Не застал','Отказ','Не подходит')),
  reason      text,
  next_step   text,
  next_date   date,
  created_at  timestamptz not null default now(),
  created_by  text,
  updated_at  timestamptz not null default now(),
  updated_by  text,
  constraint refusal_needs_reason check (result is distinct from 'Отказ' or length(trim(coalesce(reason,''))) > 0)
);

create table if not exists public.audit_log (
  id          bigint generated always as identity primary key,
  at          timestamptz not null default now(),
  actor       text not null,
  entity      text not null check (entity in ('location','visit','system')),
  entity_id   bigint,
  location_id bigint,
  action      text not null,
  summary     text not null,
  changes     jsonb
);

create index if not exists locations_type_idx  on public.locations(type_id);
create index if not exists visits_location_idx on public.visits(location_id);
create index if not exists audit_location_idx  on public.audit_log(location_id);
create index if not exists audit_at_idx        on public.audit_log(at desc);

-- ============ Кто сейчас работает ============

create or replace function public.is_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from team_members
                 where lower(email) = lower(auth.jwt() ->> 'email') and active);
$$;

create or replace function public.current_member_name() returns text
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select name from team_members where lower(email) = lower(auth.jwt() ->> 'email') and active),
    nullif(current_setting('egox.actor', true), ''),
    auth.jwt() ->> 'email',
    'система');
$$;

-- ============ Триггеры: кто и когда, запрет удаления ============

create or replace function public.stamp() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := now();
    new.created_by := public.current_member_name();
  end if;
  new.updated_at := now();
  new.updated_by := public.current_member_name();
  return new;
end $$;

create or replace function public.no_delete() returns trigger
language plpgsql as $$
begin
  raise exception 'Удалять нельзя. Поставьте статус «Отказ» или «Не подходит».';
end $$;

drop trigger if exists locations_stamp on public.locations;
create trigger locations_stamp before insert or update on public.locations
  for each row execute function public.stamp();
drop trigger if exists visits_stamp on public.visits;
create trigger visits_stamp before insert or update on public.visits
  for each row execute function public.stamp();

drop trigger if exists locations_no_delete on public.locations;
create trigger locations_no_delete before delete on public.locations
  for each row execute function public.no_delete();
drop trigger if exists visits_no_delete on public.visits;
create trigger visits_no_delete before delete on public.visits
  for each row execute function public.no_delete();
drop trigger if exists audit_no_change on public.audit_log;
create trigger audit_no_change before update or delete on public.audit_log
  for each row execute function public.no_delete();

-- ============ История изменений: локации ============

create or replace function public.audit_location() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  parts text[] := '{}';
  ch    jsonb  := '{}';
  f     record;
  o     jsonb;
  n     jsonb := to_jsonb(new);
begin
  if current_setting('egox.import', true) = '1' then return new; end if;
  if tg_op = 'INSERT' then
    insert into audit_log(actor, entity, entity_id, location_id, action, summary, changes)
    values (current_member_name(), 'location', new.id, new.id, 'добавил',
            new.name || coalesce(' · ' || new.type_id, '') || coalesce(' · ' || new.people || ' чел.', ''), n);
    return new;
  end if;
  o := to_jsonb(old);
  for f in select * from (values
      ('name','название'),('type_id','тип'),('people','людей'),('region','регион'),('owner','ведёт'),
      ('status','статус'),('contact','контакт'),('phone','телефон'),('site','площадка'),('project','проект'),
      ('hours_override','часы'),('planned_date','когда поеду'),('next_step','след. шаг'),('note','комментарий')
    ) v(col, label)
  loop
    if (o -> f.col) is distinct from (n -> f.col) then
      ch := ch || jsonb_build_object(f.col, jsonb_build_object('old', o -> f.col, 'new', n -> f.col));
      if f.col in ('note','next_step') then
        parts := parts || (f.label || ' изменён');
      else
        parts := parts || (f.label || ': ' || coalesce(o ->> f.col, '—') || ' → ' || coalesce(n ->> f.col, '—'));
      end if;
    end if;
  end loop;
  if coalesce(array_length(parts, 1), 0) = 0 then return new; end if;
  insert into audit_log(actor, entity, entity_id, location_id, action, summary, changes)
  values (current_member_name(), 'location', new.id, new.id,
          case when current_setting('egox.via_visit', true) = '1' then 'статус по итогу выезда' else 'изменил' end,
          array_to_string(parts, '; '), ch);
  return new;
end $$;

drop trigger if exists locations_audit on public.locations;
create trigger locations_audit after insert or update on public.locations
  for each row execute function public.audit_location();

-- ============ История изменений: выезды + статус локации по итогу ============

create or replace function public.audit_visit() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  new_status text;
begin
  if current_setting('egox.import', true) = '1' and tg_op = 'INSERT' then return new; end if;
  if tg_op = 'INSERT' then
    insert into audit_log(actor, entity, entity_id, location_id, action, summary, changes)
    values (current_member_name(), 'visit', new.id, new.location_id, 'запланировал выезд',
            to_char(new.visit_date, 'DD.MM') || ', едет ' || new.who || coalesce(' — ' || new.goal, ''), to_jsonb(new));
    return new;
  end if;

  if new.result is distinct from old.result and new.result is not null then
    insert into audit_log(actor, entity, entity_id, location_id, action, summary, changes)
    values (current_member_name(), 'visit', new.id, new.location_id, 'итог выезда',
            new.result || coalesce(' — «' || new.reason || '»', ''),
            jsonb_build_object('result', jsonb_build_object('old', old.result, 'new', new.result), 'reason', new.reason));
    new_status := case new.result
      when 'Договорились' then 'Договорились'
      when 'Думает'       then 'Переговоры'
      when 'Не застал'    then 'Переговоры'
      when 'Отказ'        then 'Отказ'
      when 'Не подходит'  then 'Не подходит' end;
    perform set_config('egox.via_visit', '1', true);
    update locations set status = new_status
     where id = new.location_id and status is distinct from new_status and status <> 'Запущена';
    perform set_config('egox.via_visit', '0', true);
  elsif (new.visit_date, new.who, new.goal, new.reason, new.next_step, new.next_date, new.result)
        is distinct from (old.visit_date, old.who, old.goal, old.reason, old.next_step, old.next_date, old.result) then
    insert into audit_log(actor, entity, entity_id, location_id, action, summary, changes)
    values (current_member_name(), 'visit', new.id, new.location_id, 'изменил выезд',
            to_char(new.visit_date, 'DD.MM') || ', ' || new.who || coalesce(' — ' || new.goal, ''), to_jsonb(new));
  end if;
  return new;
end $$;

drop trigger if exists visits_audit on public.visits;
create trigger visits_audit after insert or update on public.visits
  for each row execute function public.audit_visit();

-- ============ Доступ (RLS): только команда, без удаления ============

alter table public.team_members   enable row level security;
alter table public.categories     enable row level security;
alter table public.location_types enable row level security;
alter table public.locations      enable row level security;
alter table public.visits         enable row level security;
alter table public.audit_log      enable row level security;

drop policy if exists team_read  on public.team_members;
create policy team_read  on public.team_members   for select to authenticated using (public.is_member());
drop policy if exists cat_read   on public.categories;
create policy cat_read   on public.categories     for select to authenticated using (public.is_member());
drop policy if exists type_read  on public.location_types;
create policy type_read  on public.location_types for select to authenticated using (public.is_member());

drop policy if exists loc_read   on public.locations;
create policy loc_read   on public.locations for select to authenticated using (public.is_member());
drop policy if exists loc_insert on public.locations;
create policy loc_insert on public.locations for insert to authenticated with check (public.is_member());
drop policy if exists loc_update on public.locations;
create policy loc_update on public.locations for update to authenticated using (public.is_member()) with check (public.is_member());

drop policy if exists visit_read   on public.visits;
create policy visit_read   on public.visits for select to authenticated using (public.is_member());
drop policy if exists visit_insert on public.visits;
create policy visit_insert on public.visits for insert to authenticated with check (public.is_member());
drop policy if exists visit_update on public.visits;
create policy visit_update on public.visits for update to authenticated using (public.is_member()) with check (public.is_member());

drop policy if exists audit_read on public.audit_log;
create policy audit_read on public.audit_log for select to authenticated using (public.is_member());

revoke delete on public.locations, public.visits, public.audit_log from anon, authenticated;
revoke insert, update on public.audit_log, public.team_members, public.categories, public.location_types from anon, authenticated;
revoke all on public.locations, public.visits, public.audit_log, public.team_members, public.categories, public.location_types from anon;
grant execute on function public.is_member() to authenticated;

